/* 数据集里的肌群中文名有时是口语简称，统一成解剖学名称 */
const ZH_FIX = {
  肩: '三角肌', 胸: '胸大肌', 背: '背阔肌', 臀: '臀肌',
  腿: '下肢', 手臂: '手臂肌群', 核心: '核心肌群', 腰: '竖脊肌',
};

function fixZh(name) {
  const s = String(name || '').trim();
  return ZH_FIX[s] || s;
}

export function buildGuide(ex) {
  const p = detectPattern(ex.en);
  const target = fixZh(ex.targetZh);
  const secondary = (Array.isArray(ex.secondary) ? ex.secondary : []).map(fixZh).filter(Boolean);
  const equip = ex.equipZh || '';

  const focusList = [...new Set([target, ...secondary.slice(0, 2)].filter(Boolean))];
  const focus = focusList.join('、');

  const role = p.compound
    ? `典型的${p.label}复合动作`
    : `${focusList[0] || '目标肌群'}的孤立动作`;
  const placement = p.compound
    ? '安排在训练的前半段，用标准动作质量打底，再逐步加重'
    : '放在训练后段收尾，追求充分的收缩与泵感，不必一味加重';

  const summary = `${ex.zh}是${role}${equip ? `，用${equip}完成` : ''}，主要刺激${focus || '目标肌群'}。`
    + `建议${placement}；按下面的姿势要点与节奏执行，比盲目加重量更容易进步。`;

  const cautions = [];
  if (p.key === 'hinge' || p.key === 'squat') cautions.push('有腰椎或膝关节病史，请先咨询医生/教练，并从空杆或小重量开始。');
  if (p.key === 'vpush') cautions.push('肩关节活动度不足时先做肩袖激活，不要强行做到完全过顶。');
  if (p.key === 'cardio') cautions.push('有心血管疾病或长期久坐，请从低强度开始并监测心率。');
  if (ex.equip === 'body weight') cautions.push('自重动作以控制与幅度为先，次数增加到 20 次以上仍轻松时再考虑负重。');

  return {
    pattern: p.label,
    level: p.level,
    summary,
    prepare: p.prepare,
    execute: p.execute,
    breathing: p.breathing,
    tempo: p.tempo,
    mistakes: p.mistakes,
    tips: p.tips,
    cautions,
    dose: p.compound ? DOSE : DOSE_ISOLATION,
  };
}

export default buildGuide;
