function detectPattern(name = '') {
  const s = String(name).toLowerCase();
  // 「腿弯举」「腿屈伸」优先于通用 curl/extension
  const order = ['cardio', 'core', 'calf', 'triceps', 'kneeFlex', 'kneeExt', 'biceps', 'hinge', 'squat', 'vpush', 'hpush', 'vpull', 'hpull', 'raise', 'rotation'];
  if (/leg curl|hamstring curl|nordic/.test(s)) return PATTERNS.find(p => p.key === 'kneeFlex');
  if (/leg extension/.test(s)) return PATTERNS.find(p => p.key === 'kneeExt');
  for (const key of order) {
    const p = PATTERNS.find(x => x.key === key);
    if (p && p.re.test(s)) return p;
  }
  return GENERAL;
}

